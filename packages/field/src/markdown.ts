// The committed write-ups: audits/robots.md and audits/sweep.md.
import type { ShopSurvey } from "./survey.ts";

/** One shop's outcome in a sweep. Deliberately carries no findings: see `sweepMarkdown`. */
export type SweepRow = {
  id: string;
  name: string;
  /** reached-goal: got to a checkout form, account wall or payment page. */
  outcome: "reached-goal" | "stopped" | "not-auditable" | "failed";
  reached: string | null;
  steps: number;
  modelCalls: number;
  stop: string;
  runId: string;
};

export type SweepTotals = { shops: number; audited: number; likely: number; review: number; shopsWithAny: number };

const OUTCOME: Record<SweepRow["outcome"], string> = {
  "reached-goal": "Path complete",
  stopped: "Stopped early",
  "not-auditable": "Not auditable",
  failed: "Failed",
};

const VERDICT: Record<ShopSurvey["verdict"], string> = {
  crawlable: "Cart and checkout crawlable",
  "browse-only": "Product pages only",
  closed: "Nothing crawlable",
};

/** Terminal colour codes reach us through library error messages; they never belong in a document. */
export const stripAnsi = (text: string) => text.replace(/\u001b\[[0-9;]*[A-Za-z]/g, "");

/** Markdown tables break on a stray pipe, and shop names and robots rules are third-party text. */
const cell = (text: string) => stripAnsi(text).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

export function surveyMarkdown(surveys: ShopSurvey[], date: string): string {
  const browseOnly = surveys.filter((s) => s.verdict !== "crawlable");
  const rows = surveys.map((s) => {
    const allowed = s.probes.filter((p) => p.allowed).length;
    const robots = s.home.status === "unreachable" ? "unreachable" : s.home.status === "none" ? "none" : "read";
    return `| ${cell(s.name)} | ${robots} | ${s.home.allowed ? "allowed" : "**disallowed**"} | ${allowed}/${s.probes.length} | ${VERDICT[s.verdict]} |`;
  });

  const details = surveys
    .map((s) => {
      const blocked = [s.home, ...s.probes].filter((p) => !p.allowed).map((p) => `${p.label} \`${cell(p.url)}\`${p.status === "unreachable" ? " (robots.txt unreachable, so we stay out)" : ""}`);
      const lines = [`- **${cell(s.name)}** — ${VERDICT[s.verdict]}.`];
      if (blocked.length) lines.push(`  - Disallowed to us: ${blocked.join("; ")}`);
      if (s.cartRules.length) lines.push(`  - Cart-like rules in its \`robots.txt\`: ${s.cartRules.map((r) => `\`${cell(r)}\``).join(", ")}`);
      return lines.join("\n");
    })
    .join("\n");

  return `# Which shops can be audited at all

Generated by \`npm run survey\` on ${date}. **Only \`robots.txt\` was fetched** — one request per host, no shop was
crawled. Rerun it to check these numbers; they change when a shop edits its rules.

**${browseOnly.length} of ${surveys.length} shops disallow at least one of the cart or checkout paths tested.** DarkScan obeys
\`robots.txt\`, so on those it can audit product pages but not the cart or checkout, which is where drip pricing and
basket sneaking live.

The paths below are *candidates*, not necessarily each shop's real cart URL, so the survey also lists every
cart-like \`Disallow\` rule that applies to us. A shop can be "crawlable" here and still be unauditable in practice:
bot protection drops the connection whatever \`robots.txt\` says.

| Shop | robots.txt | Home page | Cart/checkout paths allowed | Verdict |
|---|---|---|---|---|
${rows.join("\n")}

## Per shop

${details}
`;
}

export function sweepMarkdown(rows: SweepRow[], totals: SweepTotals, meta: { date: string; delayMs: number; model: string | null }): string {
  const table = rows
    .map((r) => `| ${cell(r.name)} | ${OUTCOME[r.outcome]} | ${r.steps} | ${r.reached ?? "–"} | ${cell(r.stop)} |`)
    .join("\n");
  const modelCalls = rows.reduce((n, r) => n + r.modelCalls, 0);

  return `# Real-site audit sweep

One run per shop on ${meta.date}, by \`npm run sweep\`. ${meta.delayMs / 1000}s between actions, \`robots.txt\` obeyed, a user
agent that names DarkScan, guest browsing only, no account ever created, and a stop before any payment control.
Navigation was ${meta.model ? `rules first, with \`${meta.model}\` as the fallback (${modelCalls} model decisions)` : `rules only (no language model)`}.

**${totals.audited} of ${totals.shops} shops could be audited at all; on ${rows.filter((r) => r.outcome === "reached-goal").length} the agent walked the whole path to the point where an audit must stop — a checkout form, an account wall or a payment page.**

| Shop | Outcome | Steps | Ended on | Why it stopped |
|---|---|---|---|---|
${table}

## Findings

Across every shop audited, the detectors raised **${totals.likely} likely and ${totals.review} to-review potential findings**, in
${totals.shopsWithAny} of ${totals.audited} shops.

**No finding here is attributed to a shop.** One automated run is not enough to say a named company uses a dark
pattern: a person has to check the evidence, independent runs have to agree, and the shop should get a chance to
respond first (see [docs/STUDY.md](../docs/STUDY.md)). The per-shop evidence — screenshots, steps, \`report.html\` —
stays in \`runs/\`, which is not committed.

A shop with no findings has not been cleared either. Read each report's "What this audit could not see" section:
a run that never reached the cart says nothing about the cart.
`;
}
